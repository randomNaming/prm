/**
 * 把任意写法归一成标准中文国名：先查别名表，再精确对中文名，最后精确对英文名。
 * 认不出来的返回 null，调用方自行决定保留原值还是拒绝。
 */
export function normalizeCountry(value: string): string | null {
	const raw = value.trim();
	if (!raw) return null;

	const aliased = COUNTRY_ALIASES[raw] ?? COUNTRY_ALIASES[raw.toLowerCase()];
	if (aliased) return aliased;

	const byZh = COUNTRIES.find((country) => country.zh === raw);
	if (byZh) return byZh.zh;

	const byEn = COUNTRIES.find((country) => country.en.toLowerCase() === raw.toLowerCase());
	if (byEn) return byEn.zh;

	return null;
}
